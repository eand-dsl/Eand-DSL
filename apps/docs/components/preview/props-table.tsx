import type { ReactNode } from 'react';
import propsData from './props.json';

type Row = { name: string; type: string; required: boolean; default?: string; description: string };

/** JSDoc descriptions are Markdown-ish: render `code` spans as <code>, and lead with a
 *  "Deprecated" label instead of the raw `@deprecated` tag. */
function Description({ text }: { text: string }): ReactNode {
  const deprecated = /^@deprecated\b\s*/.exec(text);
  const body = deprecated ? text.slice(deprecated[0].length) : text;
  const parts = body.split(/(`[^`]+`)/g).map((s, i) =>
    s.startsWith('`') && s.endsWith('`') && s.length > 1 ? <code key={i}>{s.slice(1, -1)}</code> : s);
  return <>{deprecated ? <strong>Deprecated. </strong> : null}{parts}</>;
}

/** Static prop-reference table generated by `npm run extract:props`. */
export function PropsTable({ name }: { name: string }) {
  const rows = (propsData as Record<string, Row[]>)[name];
  if (!rows?.length) return null;
  return (
    <table>
      <thead>
        <tr><th>Prop</th><th>Type</th><th>Default</th><th>Description</th></tr>
      </thead>
      <tbody>
        {rows.map((r) => (
          <tr key={r.name}>
            <td><code>{r.name}{r.required ? '' : '?'}</code></td>
            <td><code>{r.type}</code></td>
            <td>{r.default ? <code>{r.default}</code> : '—'}</td>
            <td>{r.description ? <Description text={r.description} /> : ''}</td>
          </tr>
        ))}
      </tbody>
    </table>
  );
}
